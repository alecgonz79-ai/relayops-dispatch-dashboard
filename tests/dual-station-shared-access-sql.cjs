// This reference model exercises the intended access policy. The assertions
// above tie its important guards to SQL source; this is NOT database execution.
function model() {
  const memberships = new Map();
  const djt6 = new Set();
  const dur6 = new Set();
  const owned = new Set();
  const mirrorAccess = id => {
    const m = memberships.get(id);
    if (!m || !m.active || m.org !== org || !djt6.has(id) || dur6.has(id)) return;
    dur6.add(id);
    owned.add(id);
  };
  return {
    memberships, djt6, dur6, owned,
    backfill() { for (const id of djt6) mirrorAccess(id); },
    grantHome(id) { djt6.add(id); mirrorAccess(id); },
    revokeHome(id) { djt6.delete(id); if (owned.delete(id)) dur6.delete(id); },
    revokeDur6(id) { dur6.delete(id); owned.delete(id); },
    activate(id) { memberships.get(id).active = true; mirrorAccess(id); },
    provision(id, { anonymous = true, homeLinkEnabled = true } = {}) {
      if (!anonymous || !homeLinkEnabled) return;
      if (!memberships.has(id)) memberships.set(id, { org, active: true, role: 'dispatcher' });
      if (memberships.get(id).org === org && memberships.get(id).active) this.grantHome(id);
    },
    canRead(id, station) {
      const m = memberships.get(id);
      return !!m && m.org === org && m.active &&
        (['owner', 'ops_manager'].includes(m.role) || (station === 'DUR6' ? dur6 : djt6).has(id));
    },
    canWrite(id, station) { return this.canRead(id, station) && memberships.get(id).role !== 'viewer'; }
  };
}

